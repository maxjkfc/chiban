const PINNED_STORAGE_KEY = "chiban_pinned_reactions";
const RECENT_STORAGE_KEY = "chiban_recent_reactions";
export const MAX_PINNED_REACTIONS = 6;

export function getCustomPinnedReactions(): string[] {
  if (typeof window === "undefined") return DEFAULT_REACTION_EMOJIS;
  try {
    const raw = localStorage.getItem(PINNED_STORAGE_KEY);
    if (!raw) return DEFAULT_REACTION_EMOJIS;
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed) && parsed.length > 0) {
      return parsed.slice(0, MAX_PINNED_REACTIONS);
    }
  } catch {
    // Fall back on storage read error
  }
  return DEFAULT_REACTION_EMOJIS;
}

export function saveCustomPinnedReactions(emojis: string[]): void {
  if (typeof window === "undefined") return;
  try {
    const clean = Array.from(new Set(emojis)).slice(0, MAX_PINNED_REACTIONS);
    localStorage.setItem(PINNED_STORAGE_KEY, JSON.stringify(clean));
  } catch {
    // Ignore storage write error
  }
}

export function getRecentReactions(): string[] {
  if (typeof window === "undefined") return [];
  try {
    const raw = localStorage.getItem(RECENT_STORAGE_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed)) {
      return parsed.slice(0, 16);
    }
  } catch {
    // Fall back on error
  }
  return [];
}

export function addRecentReaction(emoji: string): void {
  if (typeof window === "undefined" || !emoji) return;
  try {
    const recents = getRecentReactions();
    const filtered = recents.filter((e) => e !== emoji);
    const updated = [emoji, ...filtered].slice(0, 16);
    localStorage.setItem(RECENT_STORAGE_KEY, JSON.stringify(updated));
  } catch {
    // Ignore storage write error
  }
}
